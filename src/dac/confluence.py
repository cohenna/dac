# Export
# =============================================================================

@dataclass
class ExportResult:
    base_page_id: str = None
    base_page_url: str = None
    created: list = field(default_factory=list)
    updated: list = field(default_factory=list)
    skipped: list = field(default_factory=list)
    built: list = field(default_factory=list)

    @property
    def changed(self):
        return bool(self.created or self.updated)


def repo_root_for(path):
    """The git top-level directory containing `path`, or `path`'s parent when not in git."""
    top = _git(["rev-parse", "--show-toplevel"], str(path))
    return Path(top) if top else Path(path).resolve().parent


def collect_diagrams(root, title_prefix="", repo_root=None):
    """
    Turn every diagram directory under `root` into a DiagramSource. `rel_path`
    is relative to `repo_root` (default: the git top-level) so permalinks work.
    """
    root = Path(root)
    repo_root = Path(repo_root) if repo_root else repo_root_for(root)
    sources = []
    for d in find_diagram_dirs(root):
        _, manifest = load_mxfile(d)
        rel = Path(os.path.relpath(d.resolve(), repo_root.resolve())).as_posix()
        sources.append(DiagramSource(
            title=f"{title_prefix}{d.name}",
            rel_path=rel,
            attachment_name=f"{sanitize_filename(d.name)}.drawio",
            xml=build_drawio_xml(d),
            tabs=[x["name"] for x in manifest.get("diagrams", [])],
        ))
    return sources


def _resolve_base_page(client, base_page_id, space_key, base_title, parent_page_id, ctx, dry_run, log):
    """Return (base_page dict, space_id, created: bool)."""
    if base_page_id:
        page = client.get_page(base_page_id)
        return page, page["spaceId"], False

    if not (space_key and base_title):
        raise ConfluenceError("Either a base page id or a space key + base page title is required.")

    space_id = client.get_space_id(space_key)
    page = client.find_page(space_id, base_title, parent_page_id)
    if page:
        return page, space_id, False

    log(f"  + base page '{base_title}' does not exist; creating")
    if dry_run:
        return {"id": "dry-run", "title": base_title, "version": {"number": 0}, "_links": {}}, space_id, True
    page = client.create_page(space_id, base_title, index_page_body([], ctx), parent_page_id)
    return page, space_id, True


def export_to_confluence(
    client,
    root,
    *,
    base_page_id=None,
    space_key=None,
    base_title=None,
    parent_page_id=None,
    title_prefix="",
    ctx=None,
    force=False,
    dry_run=False,
    update_index=True,
    out_dir=None,
    repo_root=None,
    log=print,
):
    """
    Export every diagram directory under `root` to Confluence.

    - Diagram pages are children of the base page, titled after the directory
      (with `title_prefix`). Pages are created if missing, updated only when
      the generated draw.io content changed (or `force`), and never deleted.
    - The base page body is replaced with an index unless `update_index` is
      False.
    - `out_dir`, if given, also receives the generated `.drawio` files (handy
      for CI artifacts).
    - `dry_run` performs reads only and logs what would change.
    """
    ctx = ctx or detect_git_context(root)
    result = ExportResult()
    sources = collect_diagrams(root, title_prefix, repo_root)
    if not sources:
        raise ConfluenceError(f"No diagram directories (with _manifest.yaml) found under {root}/")

    if out_dir:
        out_dir = Path(out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        for s in sources:
            path = out_dir / s.attachment_name
            path.write_text(s.xml)
            result.built.append(str(path))

    base_page, space_id, base_created = _resolve_base_page(
        client, base_page_id, space_key, base_title, parent_page_id, ctx, dry_run, log
    )
    base_id = base_page["id"]
    result.base_page_id = base_id
    result.base_page_url = client.page_url(base_page)
    message = f"DAC export from {ctx.short_commit}"
    index_entries = []

    for s in sources:
        existing = None if base_created else client.find_page(space_id, s.title, base_id)
        body = diagram_page_body(s, ctx)
        prop_value = {
            "hash": s.content_hash,
            "commit": ctx.commit,
            "generated_at": ctx.generated_at,
            "source": s.rel_path,
        }

        if existing is None:
            log(f"  + create '{s.title}'")
            result.created.append(s.title)
            status = f"created @ {ctx.short_commit}"
            if not dry_run:
                page = client.create_page(space_id, s.title, body, base_id)
                client.upload_attachment(page["id"], s.attachment_name, s.xml.encode(), message)
                client.set_property(page["id"], PROPERTY_KEY, prop_value)
        else:
            prop = client.get_property(existing["id"], PROPERTY_KEY)
            previous = (prop or {}).get("value") or {}
            if previous.get("hash") == s.content_hash and not force:
                log(f"  = unchanged '{s.title}' (last export {previous.get('commit', '?')[:7]})")
                result.skipped.append(s.title)
                status = f"unchanged since {previous.get('commit', '?')[:7]}"
            else:
                log(f"  ~ update '{s.title}'")
                result.updated.append(s.title)
                status = f"updated @ {ctx.short_commit}"
                if not dry_run:
                    client.upload_attachment(existing["id"], s.attachment_name, s.xml.encode(), message)
                    version = existing["version"]["number"] + 1
                    client.update_page(existing["id"], s.title, body, version, message)
                    client.set_property(existing["id"], PROPERTY_KEY, prop_value)

        index_entries.append({
            "title": s.title, "rel_path": s.rel_path, "tabs": len(s.tabs), "status": status,
        })

    if update_index and (result.changed or base_created or force):
        log(f"  ~ update index on base page '{base_page.get('title', base_id)}'")
        if not dry_run:
            # Re-read for the current version number: creating children doesn't
            # bump it, but a previous run in the same second might have.
            current = client.get_page(base_id)
            version = current["version"]["number"] + 1
            client.update_page(base_id, current["title"], index_page_body(index_entries, ctx), version, message)

    return result
