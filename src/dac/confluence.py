@dataclass
class GitContext:
    """Where the export came from; used for permalinks and version messages."""
    repo_url: str = None
    commit: str = None
    ref: str = None
    run_url: str = None
    generated_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    )

    @property
    def short_commit(self):
        return self.commit[:7] if self.commit else "unknown"

    def commit_url(self):
        if self.repo_url and self.commit:
            return f"{self.repo_url}/commit/{self.commit}"
        return None

    def tree_url(self, rel_path):
        """Permalink to a path in the repo at the exported commit."""
        if self.repo_url and self.commit:
            return f"{self.repo_url}/tree/{self.commit}/{rel_path}".rstrip("/")
        return None


def _git(args, cwd):
    try:
        return subprocess.check_output(["git", *args], cwd=cwd, stderr=subprocess.DEVNULL).decode().strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def normalize_repo_url(url):
    """Turn `git@github.com:o/r.git` / `https://github.com/o/r.git` into a browsable URL."""
    if not url:
        return None
    if url.startswith("git@"):
        host, _, path = url[4:].partition(":")
        url = f"https://{host}/{path}"
    if url.endswith(".git"):
        url = url[:-4]
    return url.rstrip("/")


def detect_git_context(repo_dir=".", repo_url=None, commit=None):
    """
    Build a GitContext from explicit values, GitHub Actions environment
    variables, or the local git checkout — in that order of preference.
    """
    env = os.environ
    if repo_url is None and env.get("GITHUB_SERVER_URL") and env.get("GITHUB_REPOSITORY"):
        repo_url = f"{env['GITHUB_SERVER_URL']}/{env['GITHUB_REPOSITORY']}"
    if repo_url is None:
        repo_url = _git(["remote", "get-url", "origin"], repo_dir)
    repo_url = normalize_repo_url(repo_url)

    commit = commit or env.get("GITHUB_SHA") or _git(["rev-parse", "HEAD"], repo_dir)
    ref = env.get("GITHUB_REF_NAME") or _git(["rev-parse", "--abbrev-ref", "HEAD"], repo_dir)

    run_url = None
    if env.get("GITHUB_RUN_ID") and repo_url:
        run_url = f"{repo_url}/actions/runs/{env['GITHUB_RUN_ID']}"

    return GitContext(repo_url=repo_url, commit=commit, ref=ref, run_url=run_url)


# =============================================================================
# Page content (Confluence storage format)
# =============================================================================

@dataclass
class DiagramSource:
    """A diagram directory resolved into a page title and draw.io XML."""
    title: str
    rel_path: str
    attachment_name: str
    xml: str
    tabs: list

    @property
    def content_hash(self):
        return hashlib.sha256(self.xml.encode()).hexdigest()


def _link(url, text):
    return f'<a href="{escape(url, quote=True)}">{escape(text)}</a>' if url else escape(text)


def _version_table(ctx, rows):
    cells = "".join(f"<tr><th>{escape(k)}</th><td>{v}</td></tr>" for k, v in rows)
    return f"<h2>Version</h2><table><tbody>{cells}</tbody></table>"


def _generated_note(ctx):
    return (
        '<ac:structured-macro ac:name="info"><ac:rich-text-body>'
        f"<p>{GENERATED_MARKER} from commit <code>{escape(ctx.short_commit)}</code>. "
        "Do not edit this page by hand: it is overwritten on every export.</p>"
        "</ac:rich-text-body></ac:structured-macro>"
    )


def diagram_page_body(source, ctx):
    """Storage-format body for a diagram page."""
    name = escape(source.attachment_name)
    macro = (
        '<ac:structured-macro ac:name="drawio" ac:schema-version="1">'
        f'<ac:parameter ac:name="diagramName">{name}</ac:parameter>'
        f'<ac:parameter ac:name="attachment">{name}</ac:parameter>'
        '<ac:parameter ac:name="pageSize">false</ac:parameter>'
        '<ac:parameter ac:name="lbox">true</ac:parameter>'
        "</ac:structured-macro>"
    )
    tabs = "".join(f"<li>{escape(t)}</li>" for t in source.tabs)
    rows = [
        ("Commit", _link(ctx.commit_url(), ctx.short_commit)),
        ("Branch / ref", escape(ctx.ref or "unknown")),
        ("Source", _link(ctx.tree_url(source.rel_path), source.rel_path)),
        ("Generated", escape(ctx.generated_at)),
    ]
    if ctx.run_url:
        rows.append(("Workflow run", _link(ctx.run_url, ctx.run_url)))
    rows.append(("Content hash", f"<code>{source.content_hash[:12]}</code>"))
    return (
        _generated_note(ctx)
        + macro
        + _version_table(ctx, rows)
        + f"<h2>Diagram tabs</h2><ul>{tabs}</ul>"
        + "<p>Download the draw.io file: "
        f'<ac:link><ri:attachment ri:filename="{name}" /></ac:link></p>'
    )


def index_page_body(entries, ctx):
    """Storage-format body for the base page: a table of all diagram pages."""
    rows = "".join(
        "<tr>"
        f'<td><ac:link><ri:page ri:content-title="{escape(e["title"], quote=True)}" /></ac:link></td>'
        f"<td>{_link(ctx.tree_url(e['rel_path']), e['rel_path'])}</td>"
        f"<td>{e['tabs']}</td>"
        f"<td>{escape(e['status'])}</td>"
        "</tr>"
        for e in entries
    )
    table = (
        "<table><tbody><tr><th>Diagram</th><th>Source</th><th>Tabs</th><th>Last export</th></tr>"
        f"{rows}</tbody></table>"
    )
    version_rows = [
        ("Commit", _link(ctx.commit_url(), ctx.short_commit)),
        ("Branch / ref", escape(ctx.ref or "unknown")),
        ("Generated", escape(ctx.generated_at)),
    ]
    if ctx.run_url:
        version_rows.append(("Workflow run", _link(ctx.run_url, ctx.run_url)))
    return _generated_note(ctx) + "<h2>Diagrams</h2>" + table + _version_table(ctx, version_rows)


