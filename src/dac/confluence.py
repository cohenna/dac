"""
Export diagrams to Confluence as a page hierarchy.

One *base page* holds an index; every diagram directory (a directory with a
`_manifest.yaml`) becomes a child page with the generated `.drawio` file
attached and embedded through the draw.io macro. Each page carries a
"Version" section pointing back at the git commit it was generated from, and
Confluence's own page history keeps every export as a page version.

Only the standard library is used for HTTP so DAC stays dependency-light.
Targets Confluence Cloud (REST API v2 for pages/properties, v1 for attachment
upload, which has no v2 equivalent).
"""

import base64
import hashlib
import json
import os
import subprocess
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from html import escape
from pathlib import Path
from urllib import error, parse, request

from .converter import build_drawio_xml, find_diagram_dirs, load_mxfile, sanitize_filename

PROPERTY_KEY = "dac-export"
GENERATED_MARKER = "Generated by DAC"


class ConfluenceError(Exception):
    """Raised for any failed Confluence API call."""


# =============================================================================
# HTTP client
# =============================================================================

class ConfluenceClient:
    """
    Minimal Confluence Cloud REST client.

    `base_url` is the site root, e.g. `https://example.atlassian.net`; the
    `/wiki` context path is added automatically (override with `context`).
    Authentication is HTTP basic with an Atlassian account email + API token.
    """

    def __init__(self, base_url, user, token, context="/wiki", timeout=60):
        self.base_url = base_url.rstrip("/")
        self.context = context
        self.timeout = timeout
        creds = base64.b64encode(f"{user}:{token}".encode()).decode()
        self._auth_header = f"Basic {creds}"

    # -- low level -----------------------------------------------------------

    def _url(self, path, params=None):
        url = f"{self.base_url}{self.context}{path}"
        if params:
            url += "?" + parse.urlencode({k: v for k, v in params.items() if v is not None})
        return url

    def _request(self, method, path, params=None, json_body=None, data=None, headers=None):
        hdrs = {"Authorization": self._auth_header, "Accept": "application/json"}
        body = None
        if json_body is not None:
            body = json.dumps(json_body).encode()
            hdrs["Content-Type"] = "application/json"
        elif data is not None:
            body = data
        if headers:
            hdrs.update(headers)

        req = request.Request(self._url(path, params), data=body, method=method, headers=hdrs)
        try:
            with request.urlopen(req, timeout=self.timeout) as resp:
                raw = resp.read()
        except error.HTTPError as exc:
            detail = exc.read().decode(errors="replace")[:1000]
            raise ConfluenceError(f"{method} {path} failed: HTTP {exc.code}: {detail}") from exc
        except error.URLError as exc:
            raise ConfluenceError(f"{method} {path} failed: {exc.reason}") from exc

        if not raw:
            return None
        return json.loads(raw)

    # -- spaces / pages ------------------------------------------------------

    def get_space_id(self, space_key):
        data = self._request("GET", "/api/v2/spaces", params={"keys": space_key})
        results = data.get("results", []) if data else []
        if not results:
            raise ConfluenceError(f"Space '{space_key}' not found.")
        return results[0]["id"]

    def get_page(self, page_id):
        return self._request("GET", f"/api/v2/pages/{page_id}", params={"body-format": "storage"})

    def find_page(self, space_id, title, parent_id=None):
        """Find a page by title in a space (optionally under `parent_id`)."""
        data = self._request(
            "GET", "/api/v2/pages",
            params={"space-id": space_id, "title": title, "limit": 50},
        )
        for page in (data or {}).get("results", []):
            if parent_id is None or str(page.get("parentId")) == str(parent_id):
                return page
        return None

    def create_page(self, space_id, title, body_storage, parent_id=None):
        payload = {
            "spaceId": space_id,
            "status": "current",
            "title": title,
            "body": {"representation": "storage", "value": body_storage},
        }
        if parent_id is not None:
            payload["parentId"] = str(parent_id)
        return self._request("POST", "/api/v2/pages", json_body=payload)

    def update_page(self, page_id, title, body_storage, version_number, message=""):
        payload = {
            "id": str(page_id),
            "status": "current",
            "title": title,
            "body": {"representation": "storage", "value": body_storage},
            "version": {"number": version_number, "message": message},
        }
        return self._request("PUT", f"/api/v2/pages/{page_id}", json_body=payload)

    def page_url(self, page):
        webui = (page.get("_links") or {}).get("webui", "")
        base = (page.get("_links") or {}).get("base") or f"{self.base_url}{self.context}"
        return f"{base}{webui}"

    # -- attachments (v1: v2 has no upload endpoint) -------------------------

    def upload_attachment(self, page_id, filename, content, comment="", content_type="application/xml"):
        """Create or update an attachment on a page. `content` is bytes."""
        boundary = uuid.uuid4().hex
        parts = [
            f"--{boundary}\r\n"
            f'Content-Disposition: form-data; name="file"; filename="{filename}"\r\n'
            f"Content-Type: {content_type}\r\n\r\n".encode() + content + b"\r\n",
            f"--{boundary}\r\n"
            f'Content-Disposition: form-data; name="comment"\r\n\r\n{comment}\r\n'.encode(),
            f"--{boundary}\r\n"
            f'Content-Disposition: form-data; name="minorEdit"\r\n\r\ntrue\r\n'.encode(),
            f"--{boundary}--\r\n".encode(),
        ]
        body = b"".join(parts)
        return self._request(
            "PUT", f"/rest/api/content/{page_id}/child/attachment",
            data=body,
            headers={
                "Content-Type": f"multipart/form-data; boundary={boundary}",
                "X-Atlassian-Token": "nocheck",
            },
        )

    # -- content properties --------------------------------------------------

    def get_property(self, page_id, key):
        data = self._request("GET", f"/api/v2/pages/{page_id}/properties", params={"key": key})
        results = (data or {}).get("results", [])
        return results[0] if results else None

    def set_property(self, page_id, key, value):
        existing = self.get_property(page_id, key)
        if existing is None:
            return self._request(
                "POST", f"/api/v2/pages/{page_id}/properties",
                json_body={"key": key, "value": value},
            )
        number = (existing.get("version") or {}).get("number", 1) + 1
        return self._request(
            "PUT", f"/api/v2/pages/{page_id}/properties/{existing['id']}",
            json_body={"key": key, "value": value, "version": {"number": number}},
        )


